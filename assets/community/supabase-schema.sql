-- Supabase SQL for Unbl0cked Zone community chat/posts with custom username/password auth.
-- Passwords are handled by Supabase Auth and are never stored in readable form.
-- Run this in Supabase Dashboard > SQL Editor after creating the project.
-- Re-run this file after updates; it is written to be mostly safe to run more than once.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  username text unique,
  display_name text not null default 'Member' check (char_length(display_name) between 2 and 24),
  role text not null default 'member' check (role in ('owner','admin','mod','member','banned')),
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists display_name text not null default 'Member';
alter table public.profiles add column if not exists role text not null default 'member';
alter table public.profiles add column if not exists created_at timestamptz not null default now();
create unique index if not exists profiles_username_unique on public.profiles (lower(username));

create table if not exists public.role_grants (
  username text primary key,
  role text not null check (role in ('owner','admin','mod','member','banned')),
  note text,
  created_at timestamptz not null default now()
);

create or replace function public.current_role()
returns text
language sql
security definer
stable
as $$
  select coalesce((select role from public.profiles where id = auth.uid()), 'member')
$$;

create or replace function public.set_profile_identity()
returns trigger
language plpgsql
security definer
as $$
declare
  jwt_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  jwt_username text := lower(coalesce(auth.jwt() -> 'user_metadata' ->> 'username', split_part(jwt_email, '@', 1)));
  granted_role text;
begin
  new.email := jwt_email;
  if coalesce(new.username, '') = '' then
    new.username := jwt_username;
  end if;

  select rg.role into granted_role from public.role_grants rg where lower(rg.username) = lower(new.username);

  if tg_op = 'INSERT' then
    new.role := coalesce(granted_role, 'member');
  elsif new.role is distinct from old.role and (auth.uid() is null or public.current_role() = 'owner') then
    new.role := new.role;
  else
    new.role := coalesce(granted_role, old.role);
  end if;
  return new;
end;
$$;

drop trigger if exists set_profile_identity_trigger on public.profiles;
create trigger set_profile_identity_trigger
before insert or update on public.profiles
for each row execute function public.set_profile_identity();

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.posts add column if not exists updated_at timestamptz not null default now();
alter table public.profiles add column if not exists banned_until timestamptz;
alter table public.profiles add column if not exists muted_until timestamptz;
alter table public.profiles add column if not exists warnings integer not null default 0;
alter table public.profiles add column if not exists staff_note text;

create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  target_id uuid references public.profiles(id) on delete cascade,
  action text not null check (action in ('warn','mute','unmute','kick','ban','unban')),
  reason text,
  duration_minutes integer,
  created_at timestamptz not null default now()
);

alter table public.moderation_actions enable row level security;

drop policy if exists "staff can read moderation actions" on public.moderation_actions;
drop policy if exists "staff can insert moderation actions" on public.moderation_actions;
create policy "staff can read moderation actions" on public.moderation_actions for select using (public.current_role() in ('owner','admin','mod'));
create policy "staff can insert moderation actions" on public.moderation_actions for insert with check (public.current_role() in ('owner','admin','mod'));

create or replace function public.moderate_user(target_username text, action_name text, reason_text text default null, duration_minutes integer default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_role text;
  target public.profiles%rowtype;
  until_time timestamptz;
begin
  if auth.uid() is null then
    raise exception 'not signed in';
  end if;

  actor_role := public.current_role();
  if actor_role not in ('owner','admin','mod') then
    raise exception 'staff role required';
  end if;

  select * into target from public.profiles where lower(username) = lower(target_username) limit 1;
  if target.id is null then
    raise exception 'target user not found';
  end if;

  if actor_role = 'mod' and target.role in ('owner','admin','mod') then
    raise exception 'mods cannot moderate staff';
  end if;
  if actor_role = 'admin' and target.role = 'owner' then
    raise exception 'admins cannot moderate owners';
  end if;

  if action_name in ('mute','ban') then
    until_time := case when duration_minutes is null or duration_minutes <= 0 then now() + interval '100 years' else now() + make_interval(mins => duration_minutes) end;
  end if;

  if action_name = 'warn' then
    update public.profiles set warnings = warnings + 1, staff_note = reason_text where id = target.id;
  elsif action_name = 'mute' then
    update public.profiles set muted_until = until_time, staff_note = reason_text where id = target.id;
  elsif action_name = 'unmute' then
    update public.profiles set muted_until = null, staff_note = reason_text where id = target.id;
  elsif action_name = 'ban' then
    update public.profiles set banned_until = until_time, staff_note = reason_text where id = target.id;
  elsif action_name = 'unban' then
    update public.profiles set banned_until = null, staff_note = reason_text where id = target.id;
  elsif action_name = 'kick' then
    update public.profiles set staff_note = reason_text where id = target.id;
  else
    raise exception 'unknown moderation action';
  end if;

  insert into public.moderation_actions(actor_id, target_id, action, reason, duration_minutes)
  values (auth.uid(), target.id, action_name, reason_text, duration_minutes);
end;
$$;

revoke all on function public.moderate_user(text, text, text, integer) from public;
grant execute on function public.moderate_user(text, text, text, integer) to authenticated;

